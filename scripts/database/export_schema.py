"""Export DBML from a migrated PostgreSQL catalog, or verify saved DBML.

Uses psql (local or in Compose); reads schema metadata only. Python stdlib only.
JSON retains checks, partial/expression indexes, triggers and functions which a
DBML diagram cannot fully express. Never infer a foreign key from a column name.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGETS = {
    "core": ("core", "docs/database/core/Core_v2.dbml"),
    "runtime": ("platform_runtime", "docs/database/runtime/Platform_Runtime_v1.dbml"),
    "commercial": ("commercial", "docs/database/commercial/Commercial_ControlPlane_v2.dbml"),
}


def quote(value):
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'").replace("\r", "").replace("\n", "\\n") + "'"


def identifier(value):
    return value if re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", value) else '"' + value.replace('"', '\\"') + '"'


def fields(values):
    result = ", ".join(identifier(v) for v in values)
    return "(" + result + ")" if len(values) > 1 else result


def render(catalog, schema):
    tables = [t for t in catalog["tables"] if t["schema"] == schema]
    lines = ["// GENERATED by scripts/database/export_schema.py; do not edit by hand.",
             "// Actual PostgreSQL objects only. Full SQL semantics: schema.catalog.json.",
             "Project " + schema + " {", "  database_type: 'PostgreSQL'",
             "  Note: 'Migrated PostgreSQL catalog. Cross-database identifiers are not foreign keys.'", "}", ""]
    for enum in catalog["enums"]:
        if enum["schema"] == schema:
            lines += ["Enum " + schema + "." + identifier(enum["name"]) + " {"]
            lines += ['  "' + v.replace('"', '\\"') + '"' for v in enum["values"]]
            lines += ["}", ""]
    for table in tables:
        lines += ["Table " + schema + "." + identifier(table["name"]) + " {"]
        primary = next((c["columns"] for c in table["constraints"] if c["kind"] == "p"), [])
        for column in table["columns"]:
            sql_type = column["type"]
            dbml_type = column["type_schema"] + "." + identifier(column["type_name"]) if column["is_enum"] else sql_type.replace(" ", "_")
            # DBML quoted type preserves multiword and array PostgreSQL types.
            if " " in sql_type or "[" in sql_type:
                dbml_type = '"' + sql_type + '"'
            options = ["not null" if not column["nullable"] else "null"]
            if len(primary) == 1 and column["name"] in primary:
                options.insert(0, "pk")
            notes = []
            if column["default"] is not None:
                options.append("default: `" + column["default"].replace("`", "\\`") + "`")
            if column["identity"]:
                notes.append("PostgreSQL identity: " + column["identity"])
            if column["generated"]:
                notes.append("PostgreSQL generated: " + column["generated"])
            if column["comment"]:
                notes.append(column["comment"])
            if notes:
                options.append("note: " + quote("; ".join(notes)))
            lines.append("  " + identifier(column["name"]) + " " + dbml_type + " [" + ", ".join(options) + "]")
        indexes = []
        if len(primary) > 1:
            indexes.append("    " + fields(primary) + " [pk]")
        column_names = {c["name"] for c in table["columns"]}
        for index in table["indexes"]:
            # A partial unique index is not an unconditional UNIQUE constraint.
            # DBML cannot preserve INCLUDE/opclass/predicate semantics; retain
            # exact SQL in table notes and the catalog instead of changing it.
            if index["primary"] or index["predicate"] or index["key_count"] != index["attribute_count"] or index["method"] not in ("btree", "hash"):
                continue
            if any(k not in column_names for k in index["keys"]):
                continue
            options = ["name: " + quote(index["name"]), "type: " + index["method"]]
            if index["unique"]:
                options.append("unique")
            indexes.append("    " + fields(index["keys"]) + " [" + ", ".join(options) + "]")
        if indexes:
            lines += ["  indexes {"] + indexes + ["  }"]
        notes = [table["comment"]] if table["comment"] else []
        notes += [c["name"] + ": " + c["definition"] for c in table["constraints"] if c["kind"] != "p"]
        notes += [i["definition"] for i in table["indexes"] if not i["primary"]]
        notes += [t["definition"] for t in table["triggers"]]
        if table["rls"] or table["force_rls"]:
            notes.append("Row security: " + json.dumps(table["policies"], ensure_ascii=False))
        if notes:
            lines.append("  Note: " + quote("\n".join(notes)))
        lines += ["}", ""]
    actions = {"a": "no action", "r": "restrict", "c": "cascade", "n": "set null", "d": "set default"}
    for table in tables:
        for c in table["constraints"]:
            if c["kind"] == "f":
                lines.append("Ref: " + schema + "." + identifier(table["name"]) + "." + fields(c["columns"]) + " > "
                             + c["target_schema"] + "." + identifier(c["target_table"]) + "." + fields(c["target_columns"])
                             + " [delete: " + actions[c["on_delete"]] + ", update: " + actions[c["on_update"]] + "]")
    return "\n".join(lines) + "\n"


def migration_manifest(plane):
    directory, pattern = ("apps/control-plane/migrations", "Version*.php") if plane == "commercial" else ("apps/backend/migrations/sql", "*.sql")
    return [{"path": p.relative_to(ROOT).as_posix(), "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
            for p in sorted((ROOT / directory).glob(pattern))]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plane", choices=["core", "commercial"], required=True)
    parser.add_argument("--from-snapshot", action="store_true")
    parser.add_argument("--check", action="store_true", help="Read-only comparison; exit 1 on drift")
    parser.add_argument("--psql", help="Local psql executable instead of Compose")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", default="5432")
    parser.add_argument("--database")
    parser.add_argument("--user")
    args = parser.parse_args()
    plane = args.plane
    snapshot = ROOT / "docs/database" / ("core" if plane == "core" else "commercial") / "schema.catalog.json"
    if args.from_snapshot:
        catalog = json.loads(snapshot.read_text(encoding="utf-8"))
    else:
        database = args.database or ("platform_test" if plane == "core" else "platform_commercial_test")
        user = args.user or ("platform_app" if plane == "core" else "platform_control_test")
        command = ([args.psql, "-h", args.host, "-p", str(args.port)] if args.psql else
                   ["docker", "compose", "--profile", "test" if plane == "core" else "control-test", "exec", "-T",
                    "postgres-test" if plane == "core" else "control-postgres-test", "psql"])
        command += ["-X", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-U", user, "-d", database]
        result = subprocess.run(command, input=(Path(__file__).with_name("schema_catalog.sql")).read_text(encoding="utf-8"),
                                text=True, encoding="utf-8", capture_output=True, timeout=60, check=True)
        catalog = json.loads(result.stdout)
        history_sql = ("SELECT COALESCE(json_agg(migration_name ORDER BY migration_name),'[]') FROM public.platform_migrations;" if plane == "core" else
                       "SELECT COALESCE(json_agg(version ORDER BY version),'[]') FROM public.doctrine_migration_versions;")
        history = subprocess.run(command, input=history_sql, text=True, encoding="utf-8", capture_output=True, timeout=60, check=True)
        catalog["applied_migrations"] = json.loads(history.stdout)
        catalog["migration_sources"] = migration_manifest(plane)
    if catalog.get("migration_sources") != migration_manifest(plane):
        raise SystemExit("Migration source drift: capture a fresh catalog from a fully migrated isolated database.")
    applied = sorted(v.rsplit("\\", 1)[-1] for v in catalog.get("applied_migrations", []))
    expected = sorted(Path(m["path"]).stem if plane == "commercial" else Path(m["path"]).name for m in migration_manifest(plane))
    if applied != expected:
        raise SystemExit("Applied migrations do not match the repository. Do not publish a partial schema diagram.")
    outputs = {snapshot: json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"}
    for target in (["core", "runtime"] if plane == "core" else ["commercial"]):
        schema, relative = TARGETS[target]
        outputs[ROOT / relative] = render(catalog, schema)
    if plane == "core":
        outputs[ROOT / "docs/database/core/Core_v1_FINAL.dbml"] = (
            "// Compatibility filename. The current Core schema is identical to Core_v2.dbml.\n"
            + render(catalog, "core"))
    changed = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            changed.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    print(json.dumps({"plane": plane, "tables": len(catalog["tables"]), "changed": changed, "check": args.check}))
    if args.check and changed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
