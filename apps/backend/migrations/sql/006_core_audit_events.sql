-- ============================================================================
-- 006 — Audit, Outbox, Inbox
-- Audit is business/security history, NOT technical telemetry.
-- Prometheus / OpenTelemetry / Grafana never write into audit_events.
-- ============================================================================

CREATE TABLE core.audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL DEFAULT uuidv7(),

    occurred_at timestamptz NOT NULL DEFAULT now(),
    actor_type core.audit_actor_type NOT NULL,
    actor_account_id uuid,

    action varchar(180) NOT NULL,
    resource_type varchar(180),
    resource_id varchar(160),

    request_id uuid,
    correlation_id uuid,

    ip_address inet,
    user_agent text,

    success boolean NOT NULL DEFAULT true,
    error_code varchar(120),

    before_data jsonb,
    after_data jsonb,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT fk_audit_events_actor
        FOREIGN KEY (actor_account_id)
        REFERENCES core.accounts(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_audit_events_action_not_blank CHECK (btrim(action) <> '')
);

CREATE TABLE core.outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL DEFAULT uuidv7(),

    producer_module varchar(100) NOT NULL,
    event_type varchar(220) NOT NULL,
    aggregate_type varchar(160),
    aggregate_id varchar(160),

    payload jsonb NOT NULL,
    headers jsonb NOT NULL DEFAULT '{}'::jsonb,

    correlation_id uuid,
    causation_id uuid,

    status core.outbox_status NOT NULL DEFAULT 'pending',
    attempts integer NOT NULL DEFAULT 0,

    occurred_at timestamptz NOT NULL DEFAULT now(),
    available_at timestamptz NOT NULL DEFAULT now(),
    published_at timestamptz,

    locked_by varchar(160),
    locked_until timestamptz,
    last_error text,

    CONSTRAINT chk_outbox_producer_not_blank CHECK (btrim(producer_module) <> ''),
    CONSTRAINT chk_outbox_event_type_not_blank CHECK (btrim(event_type) <> ''),
    CONSTRAINT chk_outbox_attempts CHECK (attempts >= 0)
);

CREATE TABLE core.inbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id uuid NOT NULL,
    consumer varchar(180) NOT NULL,

    status core.inbox_status NOT NULL DEFAULT 'received',
    attempts integer NOT NULL DEFAULT 0,

    received_at timestamptz NOT NULL DEFAULT now(),
    processed_at timestamptz,

    locked_by varchar(160),
    locked_until timestamptz,
    last_error text,

    CONSTRAINT chk_inbox_consumer_not_blank CHECK (btrim(consumer) <> ''),
    CONSTRAINT chk_inbox_attempts CHECK (attempts >= 0)
);
