import { mkdirSync, writeFileSync } from 'node:fs';
import { launchBrowser, stableScreenshot } from './e2e-support.mjs';

const base = process.env.BASE_URL ?? 'http://127.0.0.1:5173';
const browser = await launchBrowser();
const errors = [];
const checks = [];
const check = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
mkdirSync('screenshots', { recursive: true });
function observe(page) {
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
}
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  await context.addInitScript(() => { localStorage.setItem('platform.locale', 'en'); localStorage.setItem('platform.theme', 'light'); });
  const page = await context.newPage(); observe(page);
  await page.goto(`${base}/settings/components`, { waitUntil: 'networkidle' });
  const all = page.locator('#demo-check-all');
  check(await all.evaluate(input => input.indeterminate), 'Native mixed checkbox state');
  await page.getByText('Select all', { exact: true }).click();
  check(await page.locator('#demo-check-first').isChecked() && await page.locator('#demo-check-second').isChecked(), 'Whole label selects both children');
  await all.focus(); await page.keyboard.press('Space');
  check(!await page.locator('#demo-check-first').isChecked() && !await page.locator('#demo-check-second').isChecked(), 'Keyboard Space clears the group');
  await page.getByText('First option', { exact: true }).click();
  check(await all.evaluate(input => input.indeterminate), 'Partial selection restores native mixed state');
  check(await page.locator('#demo-check-disabled').isDisabled() && await page.locator('#demo-switch-disabled').isDisabled(), 'Disabled controls remain native and unfocusable');
  const toggle = page.locator('#demo-switch');
  await toggle.focus(); await page.keyboard.press('Space');
  check(!await toggle.isChecked(), 'Switch works with keyboard Space');
  await page.getByText('Example switch', { exact: true }).click();
  check(await toggle.isChecked(), 'Switch works from its full label');
  const nativeForm = page.locator('#demo-native-form');
  const formName = page.locator('#demo-form-name');
  await formName.fill('Audit');
  const formData = await nativeForm.evaluate(form => Object.fromEntries(new FormData(form).entries()));
  check(formData.username === 'Audit' && formData.updates === 'on', 'Native form attributes and values stay on the real controls');
  await page.locator('#demo-form-reset').click();
  await page.waitForFunction(() => document.querySelector('#demo-form-name')?.value === '');
  check(await formName.inputValue() === '' && !await page.locator('#demo-form-updates').isChecked(), 'Native reset restores the control state');
  const restored = (await page.locator('#demo-form-model').textContent())?.replace(/\s+/g, ' ').trim() ?? '';
  check(restored.includes('—') && restored.endsWith('off'), `Native reset restores the Vue state: ${restored}`);
  await formName.fill('Audit');
  await page.locator('#demo-form-updates').check();
  await page.evaluate(() => {
    const form = document.querySelector('#demo-native-form');
    form?.addEventListener('reset', event => event.preventDefault(), { once: true });
  });
  await page.locator('#demo-form-reset').click();
  await page.waitForTimeout(100);
  check(await formName.inputValue() === 'Audit' && await page.locator('#demo-form-updates').isChecked(), 'Canceled native reset leaves the control state unchanged');
  const canceled = (await page.locator('#demo-form-model').textContent())?.replace(/\s+/g, ' ').trim() ?? '';
  check(canceled.includes('Audit') && canceled.endsWith('on'), `Canceled native reset leaves the Vue state unchanged: ${canceled}`);
  await page.locator('#demo-form-reset').click();
  await page.waitForFunction(() => document.querySelector('#demo-form-name')?.value === '');
  check(await formName.inputValue() === '' && !await page.locator('#demo-form-updates').isChecked(), 'A later native reset still works');
  const sortable = page.locator('#demo-sortable');
  await sortable.waitFor();
  const sortableBefore = await sortable.locator('.sortable__label').allTextContents();
  await sortable.locator('.sortable__handle').first().focus();
  await page.keyboard.press('Alt+ArrowDown');
  await page.waitForTimeout(100);
  const sortableAfter = await sortable.locator('.sortable__label').allTextContents();
  check(sortableAfter[0] === sortableBefore[1] && sortableAfter[1] === sortableBefore[0], 'Sortable list reorders with Alt+ArrowDown');
  check(await page.evaluate(() => getComputedStyle(document.querySelector('label')).userSelect) === 'none', 'Labels are protected from text selection');

  const control = page.locator('label[for="demo-switch"] .app-switch__control');
  const point = await control.boundingBox();
  await page.mouse.move(point.x + point.width / 2, point.y + point.height / 2); await page.mouse.down();
  await page.waitForFunction(() => parseFloat(getComputedStyle(document.querySelector('#demo-switch + .app-switch__track .app-switch__thumb')).width) > 27);
  check(true, 'Switch thumb expands during a real press');
  await page.mouse.up();
  await stableScreenshot(page, 'screenshots/controls-desktop-light.png');
  await page.goto(`${base}/settings`, { waitUntil: 'networkidle' });
  const slider = page.locator('#appearance-font-scale');
  await slider.scrollIntoViewIfNeeded();
  const box = await slider.boundingBox();
  await page.mouse.move(box.x + 12 + (box.width - 24) * .2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + 12 + (box.width - 24) * .7, box.y + box.height / 2, { steps: 12 });
  check(await slider.evaluate(input => Number(input.value) >= 1.2), 'Native slider follows real pointer dragging');
  check(await slider.evaluate(input => getComputedStyle(input).getPropertyValue('--range-thumb-scale').trim()) === '1.28', 'Slider thumb grows during press');
  const rangeGroup = page.locator('.app-range:has(#appearance-font-scale)');
  await rangeGroup.scrollIntoViewIfNeeded();
  await rangeGroup.screenshot({ path: 'screenshots/controls-slider-pressed.png', animations: 'disabled' });
  // Releasing outside the range must still finish the edit through native pointer capture.
  await page.mouse.move(box.x + box.width + 50, box.y - 40); await page.mouse.up();
  check(!await page.locator('.app-range--pressed').count(), 'Release outside slider clears pressed state');
  await page.locator('#appearance-undo').click();
  check(await slider.inputValue() === '1', 'A complete drag is undone in one step');
  await slider.focus(); await page.keyboard.press('End');
  check(await slider.inputValue() === '1.4', 'Keyboard End reaches the range maximum');
  await page.keyboard.press('Home');
  check(await slider.inputValue() === '0.9', 'Keyboard Home reaches the range minimum');
  await page.locator('#appearance-reset').click();
  await page.locator('#appearance-animations').uncheck();
  check(await page.locator('#appearance-speed').isDisabled(), 'Animation switch disables dependent settings');
  await page.reload({ waitUntil: 'networkidle' });
  check(!await page.locator('#appearance-animations').isChecked(), 'Switch setting survives a reload');
  await page.locator('#appearance-animations').check();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check(await page.locator('.app-switch__thumb').first().evaluate(element => getComputedStyle(element).transitionDuration.split(',').every(value => parseFloat(value) === 0)), 'Reduced motion removes switch transitions');
  check(await page.locator('#appearance-speed').isDisabled(), 'OS reduced motion keeps dependent settings disabled');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('#appearance-advanced summary').click();
  await page.screenshot({ path: 'screenshots/controls-settings-light.png', fullPage: true, animations: 'disabled' });
  await page.getByLabel('Dark', { exact: true }).check();
  await page.waitForFunction(() => !document.documentElement.hasAttribute('data-theme-changing'));
  await page.screenshot({ path: 'screenshots/controls-settings-dark.png', fullPage: true, animations: 'disabled' });
  await page.goto(`${base}/settings/components`, { waitUntil: 'networkidle' });
  await stableScreenshot(page, 'screenshots/controls-desktop-dark.png');
  await context.close();

  const mobile = await browser.newContext({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  await mobile.addInitScript(() => { localStorage.setItem('platform.locale', 'ru'); localStorage.setItem('platform.theme', 'dark'); });
  const touch = await mobile.newPage(); observe(touch);
  await touch.goto(`${base}/settings/components`, { waitUntil: 'networkidle' });
  await touch.locator('label[for="demo-switch"]').tap();
  check(!await touch.locator('#demo-switch').isChecked(), 'Switch responds to touch across the whole label');
  await touch.locator('label[for="demo-check-all"]').tap();
  check(await touch.locator('#demo-check-first').isChecked() && await touch.locator('#demo-check-second').isChecked(), 'Checkbox group responds to touch');
  for (const [index, name] of [[0, 'controls-mobile-ru'], [1, 'controls-mobile-switch']]) {
    const card = touch.locator('.components-view__grid').first().locator('.app-card').nth(index);
    await card.evaluate(element => window.scrollTo(0, element.getBoundingClientRect().top + scrollY - 80));
    await card.screenshot({ path: `screenshots/${name}.png`, animations: 'disabled' });
  }
  await touch.goto(`${base}/settings`, { waitUntil: 'networkidle' });
  const range = touch.locator('#appearance-font-scale'); await range.scrollIntoViewIfNeeded();
  const touchBox = await range.boundingBox();
  const cdp = await mobile.newCDPSession(touch);
  const y = touchBox.y + touchBox.height / 2;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: touchBox.x + 12 + (touchBox.width - 24) * .2, y }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: touchBox.x + 12 + (touchBox.width - 24) * .8, y }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  check(Number(await range.inputValue()) >= 1.25, 'Native range follows real touch dragging');
  check(!await touch.locator('.app-range--pressed').count(), 'Touch release clears pressed state');
  await touch.locator('#appearance-reset').click();
  await range.scrollIntoViewIfNeeded();
  await stableScreenshot(touch, 'screenshots/controls-mobile-slider.png');
  await touch.setViewportSize({ width: 320, height: 740 });
  await range.focus(); await touch.keyboard.press('End');
  check(await touch.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), '320px with 140% text has no horizontal overflow');
  await stableScreenshot(touch, 'screenshots/controls-320-large-text.png');
  await mobile.close();
  check(errors.length === 0, `No browser errors: ${errors.join('; ')}`);
  writeFileSync('screenshots/controls-results.json', JSON.stringify({ passed: true, checks }, null, 2));
  console.log(`CONTROL CHECKS PASSED: ${checks.length} assertions; keyboard, mouse, touch, persistence and reduced motion.`);
} finally { await browser.close(); }
