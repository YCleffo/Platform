import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const directory = join(root, 'src/shared/ui/icons');
const sources = join(directory, 'svg');
const symbols = readdirSync(sources).filter((file) => file.endsWith('.svg')).sort().map((file) => {
  const id = file.slice(0, -4);
  if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`Invalid icon name: ${file}`);
  const source = readFileSync(join(sources, file), 'utf8').replace(/\r\n/g, '\n').trim();
  const match = /^<svg\b([^>]*)>([\s\S]*)<\/svg>$/.exec(source);
  if (match === null || !/viewBox="0 0 24 24"/.test(match[1])) throw new Error(`Invalid SVG: ${file}`);
  if (/<(?:script|foreignObject|style|image)\b|\bon[a-z]+\s*=|\bhref\s*=|\bid\s*=|url\s*\(/i.test(source)) {
    throw new Error(`Icon must contain only self-contained SVG artwork: ${file}`);
  }
  if (/#[0-9a-f]{3,8}\b/i.test(source)) throw new Error(`Use currentColor: ${file}`);
  return `  <symbol id="${id}" viewBox="0 0 24 24" fill="none">${match[2].trim()}</symbol>`;
});
const output = `<!-- Generated by npm run generate:icons. Solar artwork: ./NOTICE.md -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
const target = join(directory, 'sprite.svg');
const references = [...readFileSync(join(directory, 'index.ts'), 'utf8').matchAll(/icon\('([^']+)'\)/g)]
  .map((match) => match[1]);
const names = readdirSync(sources).filter((file) => file.endsWith('.svg')).map((file) => file.slice(0, -4));
if (references.some((name) => !names.includes(name)) || names.some((name) => !references.includes(name))) {
  throw new Error('Named icon exports must match the selected SVG sources');
}
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('SVG sprite is stale; run npm run generate:icons');
  console.log(`PASS local SVG sprite: ${symbols.length} symbols`);
} else {
  writeFileSync(target, output);
  console.log(`Generated ${symbols.length} local SVG symbols`);
}
