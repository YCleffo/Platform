import { launchBrowser, navigateClientSide } from './e2e-support.mjs';
const browser = await launchBrowser();
const context = await browser.newContext({ viewport: { width: 1440, height: 800 } });
await context.addInitScript(() => localStorage.setItem('platform.locale', 'en'));
const page = await context.newPage();
const errors = [];
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
page.on('pageerror', error => errors.push(String(error)));
await page.goto('http://127.0.0.1:4176/admin/login', { waitUntil: 'networkidle' });
const settingsOnAuth = await page.getByRole('button', { name: 'Settings', exact: true }).count();
await page.locator('#admin-identifier').fill('ura.nikogosuan@gmail.com');
await page.locator('#admin-password').fill('OwnerAdmin2026!');
await page.getByRole('button', { name: 'Sign in', exact: true }).click();
await page.waitForURL('**/admin', { timeout: 20_000 });
await page.getByRole('heading', { name: 'Platform overview' }).waitFor({ timeout: 20_000 });
await page.waitForTimeout(600);
const markBefore = await page.locator('.admin__mark').boundingBox();
await page.getByRole('button', { name: 'Collapse sidebar' }).click();
await page.waitForTimeout(350);
const collapsed = {
  width: (await page.locator('.admin__sidebar').boundingBox())?.width,
  mark: await page.locator('.admin__mark').boundingBox(),
  labelWidth: await page.locator('.admin__link-label').first().evaluate(el => getComputedStyle(el).maxWidth),
};
await page.locator('.admin__link').first().hover();
await page.waitForTimeout(100);
const tooltip = await page.locator('.app-tooltip__bubble').first().innerText();
await page.screenshot({ path: 'screenshots/admin-collapsed-tooltip.png' });
await page.getByRole('button', { name: 'Expand sidebar' }).click();
await page.waitForTimeout(350);
await navigateClientSide(page, '/admin/accounts');
await page.locator('.admin-resource__table tbody tr').first().waitFor({ timeout: 20_000 });
const pageSizeBefore = await page.locator('#admin-page-size').innerText();
await page.locator('#admin-page-size').click();
await page.locator('[data-menu-id="50"]').click();
await page.waitForTimeout(300);
const pageSizeAfter = await page.locator('#admin-page-size').innerText();
await navigateClientSide(page, '/admin/audit');
await page.getByRole('heading', { name: 'Core audit log', level: 2 }).waitFor({ timeout: 20_000 });
await page.locator('.admin-resource__table tbody tr').first().waitFor({ timeout: 20_000 });
await page.waitForTimeout(500);
const scrollInfo = await page.evaluate(() => ({ bodyOverflow: getComputedStyle(document.body).overflow, docOverflow: getComputedStyle(document.documentElement).overflow, scrollHeight: document.documentElement.scrollHeight, bodyHeight: document.body.scrollHeight, innerHeight: window.innerHeight, mainScrollHeight: document.querySelector('.admin__main')?.scrollHeight, mainOverflow: document.querySelector('.admin__main') ? getComputedStyle(document.querySelector('.admin__main')).overflow : null }));
console.log('SCROLL_INFO', scrollInfo);
await page.evaluate(() => window.scrollTo(0, 900));
await page.waitForTimeout(300);
const scrollY = await page.evaluate(() => window.scrollY);
const headerTop = (await page.locator('.admin-resource__table thead th').first().boundingBox())?.y;
const topbarHeight = (await page.locator('.admin__topbar').boundingBox())?.height;
console.log(JSON.stringify({ settingsOnAuth, collapsed, markBefore, tooltip, pageSizeBefore, pageSizeAfter, scrollY, headerTop, topbarHeight, errors }, null, 2));
await browser.close();
